//! Goldilocks field arithmetic and the two constants that define copy-argument
//! labels, shared by the compiler and the checkers.
use serde::{Deserialize, Serialize};

/// The Goldilocks prime `2^64 - 2^32 + 1`, the only supported field.
pub const GOLDILOCKS_PRIME: u64 = 0xffff_ffff_0000_0001;
/// Short name for [`GOLDILOCKS_PRIME`] inside the crate.
pub(crate) const P: u64 = GOLDILOCKS_PRIME;

/// A field element below `P`, serialized as a decimal string.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct FieldElement(pub u64);
impl TryFrom<String> for FieldElement {
    type Error = String;
    fn try_from(s: String) -> std::result::Result<Self, String> {
        let value: u64 = s
            .parse()
            .map_err(|_| "field element is not a decimal number")?;
        if value >= P || value.to_string() != s {
            return Err("field element must be below P, without leading zeros or sign".into());
        }
        Ok(Self(value))
    }
}
impl From<FieldElement> for String {
    fn from(x: FieldElement) -> Self {
        x.0.to_string()
    }
}

/// Generator of the multiplicative group. The row domain of size `n` is
/// generated by `GENERATOR^((P - 1) / n)`.
pub const GENERATOR: u64 = 7;
/// Copy-argument label factor: the cell at row `r` and column `c` has label
/// `ω^r · COSET^c`, where `ω` generates the row domain.
pub const COSET: u64 = 12_275_445_934_081_160_404;

/// `a + b` for field elements below `P`.
pub fn add(a: u64, b: u64) -> u64 {
    ((u128::from(a) + u128::from(b)) % u128::from(P)) as u64
}
/// `a · b` for field elements below `P`.
pub fn mul(a: u64, b: u64) -> u64 {
    ((u128::from(a) * u128::from(b)) % u128::from(P)) as u64
}
/// `-a` for a field element below `P`.
pub fn neg(a: u64) -> u64 {
    if a == 0 {
        0
    } else {
        P - a
    }
}
/// `x^n` by square-and-multiply.
pub fn pow(mut x: u64, mut n: u64) -> u64 {
    let mut result = 1;
    while n != 0 {
        if n & 1 != 0 {
            result = mul(result, x);
        }
        x = mul(x, x);
        n >>= 1;
    }
    result
}
/// Multiplicative inverse `x^(P - 2)`.
///
/// # Panics
/// If `x` is zero, which has no inverse.
pub fn inverse(x: u64) -> u64 {
    assert!(x != 0, "zero has no inverse");
    pow(x, P - 2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn domain_constants_are_pinned() {
        assert_eq!(GENERATOR, 7);
        assert_eq!(COSET, 12_275_445_934_081_160_404);
        // The generator has order P - 1: no power (P - 1) / q is one, for each
        // prime factor q of P - 1 = 2^32 * 3 * 5 * 17 * 257 * 65537.
        for q in [2, 3, 5, 17, 257, 65537] {
            assert_ne!(pow(GENERATOR, (P - 1) / q), 1);
        }
        // COSET is not in the largest supported row domain (size 2^16).
        assert_ne!(pow(COSET, 1 << 16), 1);
    }

    #[test]
    fn inverse_and_arithmetic() {
        for x in [1, 2, 7, COSET, P - 1] {
            assert_eq!(mul(x, inverse(x)), 1);
            assert_eq!(add(x, neg(x)), 0);
        }
    }
}
